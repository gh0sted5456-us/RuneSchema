#include "Runtime/BuildingPolicy/NativeExecTarget.h"
#include <cassert>
#include <vector>
using namespace PS::Buildings;
int main(){
    // Save the exec result pointer; WinGDK's FFrame helpers use both indirect call forms.
    const std::vector<unsigned char> thunk{0x4c,0x89,0xc3,0xff,0xd0,0xff,0x50,0x10,0xe8,0x20,0,0,0,0x88,0x03,0xe8,0x40,0,0,0,0xc3};
    assert(NativeExecTarget(0x1000,thunk,1)==0x102d); // The cleanup call cannot replace the result producer.
    auto integer=thunk;integer[13]=0x89;assert(NativeExecTarget(0x1000,integer,4)==0x102d);
    const std::vector<unsigned char> steam{0x4c,0x89,0xc3,0xe8,0x20,0,0,0,0x88,0x03,0xc3};
    assert(NativeExecTarget(0x1000,steam,1)==0x1028);
    const auto rejected=[](std::vector<unsigned char> bytes,unsigned size){bool failed=false;try{NativeExecTarget(0x1000,bytes,size);}catch(const std::exception&){failed=true;}assert(failed);};
    rejected({0x4c,0x89,0xc3,0xff,0xd0,0x88,0x03,0xc3},1); // An indirect result producer is still unsupported.
    rejected({0x4c,0x89,0xc3,0xe8,0x20,0,0,0,0x31,0xc0,0x88,0x03,0xc3},1); // A rewritten result is not attributed to the call.
    rejected({0x4c,0x89,0xc3,0xe8,0x20,0,0,0,0x88,0x03,0xff,0xd0,0x88,0x03,0xc3},1);
    rejected({0x4c,0x89,0xc3,0xe8,0x20,0,0,0,0x88,0x03,0xe8,0x30,0,0,0,0x88,0x03,0xc3},1);
    rejected({0xe8,0x20,0,0,0,0x41,0x88,0x00,0xc3},1); // Volatile R8 does not retain the result pointer across a call.
    rejected({0xe8},1);rejected({},1);rejected(thunk,2);
    const std::vector<unsigned char> tail{0xff,0xd0,0xe9,0x20,0,0,0};
    assert(NativeExecTarget(0x1000,tail,0)==0x1027);
    rejected({0xff,0xe0},0); // An unknown tail target must never be detoured.
}
